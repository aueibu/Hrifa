/** M7a: the chord library (SCENARIOS.M7.md rows 1 to 15 for the data and the logic), computed through the real lib. */
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  CHORD_LIBRARY_CREDIT,
  FOLD_REASON,
  TEMPLATE_LIMIT,
  TEMPLATE_NAME_MAX,
  addLibraryEntries,
  entryInfo,
  filterLibrary,
  joinNames,
  libraryEntries,
  libraryShapes,
  librarySummary,
  type LibraryEntry,
} from './chordLibrary';
import { CHORD_LIBRARY_DATA } from './chordLibraryData';
import { DEFAULT_TEMPLATES, parseTemplate, templateKey, type ChordTemplate } from './chords';

const entries = libraryEntries(1200);
const shapes = libraryShapes(entries, 1200);
const byText = (t: string): LibraryEntry => {
  const e = entries.find((x) => x.text === t);
  if (!e) {
    throw new Error(`no entry ${t}`);
  }
  return e;
};
const shapeOf = (t: string) => shapes.find((s) => s.entries.some((e) => e.text === t));
const texts = (t: string) => (shapeOf(t)?.entries ?? []).map((e) => e.text);

describe('the generated data', () => {
  it('carries the credit in its header and has the 399 colon-ratio entries', () => {
    const src = readFileSync(new URL('./chordLibraryData.ts', import.meta.url), 'utf8');
    const head = src.slice(0, src.indexOf('*/'));
    expect(head).toContain('Generated by arcs/harmonic-field-lab/scripts/build_chord_library.py');
    expect(head).toContain(
      '"List of chords for Scala" by Manuel Op de Coul (Scala). Do not edit by hand.'
    );
    expect(head).toContain(CHORD_LIBRARY_CREDIT);
    expect(CHORD_LIBRARY_CREDIT).toBe('Chord list by Manuel Op de Coul, from Scala (chordnam.par)');
    expect(CHORD_LIBRARY_DATA).toHaveLength(399);
  });

  it('every text parses, and the undertone entries parse as undertones', () => {
    const bad = CHORD_LIBRARY_DATA.filter((e) => !parseTemplate(e.text).ok).map((e) => e.text);
    expect(bad).toEqual([]);
    const under = CHORD_LIBRARY_DATA.filter((e) => e.text.startsWith('1/('));
    expect(under).toHaveLength(7);
    for (const e of under) {
      const p = parseTemplate(e.text);
      expect(p.ok && p.utonal).toBe(true);
    }
    expect(CHORD_LIBRARY_DATA.filter((e) => !e.text.startsWith('1/('))).toHaveLength(392);
  });

  it('families come out as the confirmed counts', () => {
    const n: Record<string, number> = {};
    for (const e of CHORD_LIBRARY_DATA) {
      n[e.family] = (n[e.family] ?? 0) + 1;
    }
    expect(n).toEqual({
      'Named chords': 49,
      'Neo-Medieval (NM)': 47,
      Pentachords: 39,
      'Sevenths, ninths and added tones': 37,
      'Diminished and augmented': 37,
      Tetrachords: 31,
      'Neutral, subminor and supermajor': 30,
      'Harmonics and subharmonics': 23,
      Minor: 22,
      Major: 17,
      'Hendrix chords': 16,
      Trichords: 11,
      'Septimal and higher limits': 7,
      'Number sequences': 6,
      'Bohlen-Pierce (BP)': 6,
      'Saturated suspensions (ASS)': 6,
      'Suspended and quartal': 6,
      'Genus and product sets': 5,
      Library: 4,
    });
  });

  it('drops the leading = of a name (row 13)', () => {
    expect(CHORD_LIBRARY_DATA.find((e) => e.text === '2:3:4')?.name).toBe(
      '8/5 Chord, NM Trine "8|5-4"'
    );
    expect(CHORD_LIBRARY_DATA.some((e) => e.name.startsWith('='))).toBe(false);
  });
});

describe('libraryEntries and libraryShapes in 2/1 (rows 1, 6, 11, 12)', () => {
  it('the counts, as the real lib computes them', () => {
    // 399 lines: 16 fold; 383 usable lines make 360 rooted entries (the lab's templateKey takes the lowest pitch as the
    // root of an undertone line, so 1/(3:4:5:7), 1/(4:5:6:7) and 60:70:84:105 are ONE entry: 360, not the 362 a first
    // script counted with the first number as the root)
    expect(entries.filter((e) => e.folds)).toHaveLength(16);
    expect(entries.filter((e) => !e.folds)).toHaveLength(360);
    expect(entries).toHaveLength(376);
    expect(entries.reduce((s, e) => s + e.lines, 0)).toBe(399);
    const merged = entries.filter((e) => e.lines > 1);
    expect(merged).toHaveLength(19);
    expect(merged.reduce((s, e) => s + e.lines - 1, 0)).toBe(23);
  });

  it('merges the same root and notes into one entry with the names joined', () => {
    const genus = byText('1:3:5:15');
    expect(genus.names).toEqual(['Genus [35]', 'Major Seventh']);
    expect(entries.some((e) => e.text === '8:10:12:15')).toBe(false);
    expect(byText('3:5:7').names).toEqual([
      'BP Wide Triad',
      'Diminished Triad, Odim 1st inversion',
    ]);
    expect(entries.some((e) => e.text === '6:7:10')).toBe(false);
    expect(byText('1/(3:4:5:7)').lines).toBe(3);
    // a repeated name is kept once
    expect(byText('3:7:15:21').names).toEqual(['15-Limit ASS 1', 'Hendrix Chord (Erlich)']);
    expect(byText('3:7:15:21').lines).toBe(3);
  });

  it('shapes: 297 with a root, the sizes of their groups, and the folding entries on their own', () => {
    const rooted = shapes.filter((s) => !s.entries[0].folds);
    expect(rooted).toHaveLength(297);
    const sizes: Record<number, number> = {};
    for (const s of rooted) {
      sizes[s.entries.length] = (sizes[s.entries.length] ?? 0) + 1;
    }
    // one three-entry shape became a one-entry shape with the undertone merge (see above): 259/20/11/7
    expect(sizes).toEqual({ 1: 259, 2: 20, 3: 11, 4: 7 });
    expect(shapes).toHaveLength(313);
    expect(shapes.filter((s) => s.entries[0].folds).every((s) => s.entries.length === 1)).toBe(
      true
    );
    expect(librarySummary(shapes)).toEqual({
      entries: 376,
      lines: 399,
      shapes: 313,
      rooted: 297,
      folding: 16,
    });
  });

  it('root position first, then the inversions (rows 3, 4, 5)', () => {
    expect(texts('10:12:15')).toEqual(['10:12:15', '12:15:20', '15:20:24']);
    expect(texts('4:5:6:7')).toEqual(['4:5:6:7', '5:6:7:8', '6:7:8:10', '7:8:10:12']);
    expect(texts('4:5:6')).toEqual(['4:5:6', '5:6:8', '3:4:5']);
    expect(shapeOf('4:5:6')?.entries[0].names).toEqual(['Major Triad']);
    expect(shapeOf('3:4:5')?.entries[2].names[0]).toContain('Major Triad 2nd inversion');
    expect(texts('1:3:5:15')).toEqual(['1:3:5:15', '10:12:15:16', '12:15:16:20', '15:16:20:24']);
  });

  it('folding entries are marked, with their reason available (rows 11, 12)', () => {
    for (const t of ['1:2:3', '1:2:3:4:5:6:7:8']) {
      expect(byText(t).folds).toBe(true);
    }
    expect(byText('1:2:3').names).toEqual(['Triunisonus']);
    const sub = byText('1/(1:2:3:4:5:6:7:8)');
    expect(sub.names).toEqual(['Subharmonics 1-8']);
    expect(sub.folds).toBe(true);
    const p = parseTemplate(sub.text);
    expect(p.ok && p.utonal).toBe(true);
    expect(FOLD_REASON).toBe(
      'Two notes land on the same pitch in this repeat, so it cannot be found.'
    );
    expect(entries.filter((e) => e.folds).map((e) => e.text)).toContain('1/(1:2:3:4:5:6:7:8)');
  });

  it('the library follows the repeat: 3/1 folds 1:3:5:15, 2/1 does not', () => {
    const e3 = libraryEntries(1901.955);
    expect(e3.find((e) => e.text === '1:3:5:15')?.folds).toBe(true);
    expect(libraryEntries(1200)).toBe(entries);
  });
});

describe('entryInfo', () => {
  it('note count, odd limit and prime limit from the numbers in lowest terms', () => {
    expect(entryInfo('4:5:6')).toEqual({ notes: 3, oddLimit: 5, primeLimit: 5 });
    expect(entryInfo('4:5:6:7')).toEqual({ notes: 4, oddLimit: 7, primeLimit: 7 });
    expect(entryInfo('10:12:15')).toEqual({ notes: 3, oddLimit: 15, primeLimit: 5 });
    expect(entryInfo('6:8:9')).toEqual({ notes: 3, oddLimit: 9, primeLimit: 3 });
    expect(entryInfo('8:10:12')).toEqual({ notes: 3, oddLimit: 5, primeLimit: 5 });
    expect(entryInfo('1:2:3:4:5:6:7:8')).toEqual({ notes: 8, oddLimit: 7, primeLimit: 7 });
  });

  it('an undertone entry uses the numbers of its colon form', () => {
    expect(entryInfo('1/(1:2:3:4:5:6:7:8)')).toEqual(entryInfo('1:2:3:4:5:6:7:8'));
    expect(entryInfo('1/(4:5:6:7)')).toEqual(entryInfo('4:5:6:7'));
  });

  it('is null for a text that is not a template', () => {
    expect(entryInfo('nonsense')).toBeNull();
  });

  it('every entry carries it', () => {
    expect(byText('1:3:5:15')).toMatchObject({ notes: 4, oddLimit: 15, primeLimit: 5 });
    expect(byText('4:5:6')).toMatchObject({
      notes: 3,
      oddLimit: 5,
      primeLimit: 5,
      family: 'Major',
    });
  });
});

describe('filterLibrary (rows 2, 4, 6, 14)', () => {
  const heads = (f: Parameters<typeof filterLibrary>[1]) =>
    filterLibrary(shapes, f).map((s) => s.entries[0].text);

  it('no filter keeps every shape and flags every entry', () => {
    const all = filterLibrary(shapes, {});
    expect(all).toHaveLength(313);
    expect(all.every((s) => s.entries.every((e) => e.match))).toBe(true);
  });

  it('search matches a name or the ratio text, ignoring case', () => {
    expect(heads({ search: 'GENUS [35]' })).toEqual(['1:3:5:15']);
    expect(heads({ search: '4:5:6:7' })).toContain('4:5:6:7');
    expect(heads({ search: 'harmonic dominant seventh' })).toEqual(['4:5:6:7']);
  });

  it('a shape stays when one of its entries matches, and the matching ones are flagged', () => {
    const [s] = filterLibrary(shapes, { search: 'Genus [35]' });
    expect(s.entries.map((e) => [e.text, e.match])).toEqual([
      ['1:3:5:15', true],
      ['10:12:15:16', false],
      ['12:15:16:20', false],
      ['15:16:20:24', false],
    ]);
  });

  it('"minor triad" finds every name that contains it, among them the Minor Triad shape with its 3 entries', () => {
    // the words also occur in Subminor Triad, Supraminor Triad and Quasi-Equal Minor Triad: 11 shapes
    const found = filterLibrary(shapes, { search: 'minor triad' });
    expect(found).toHaveLength(11);
    const minor = found.find((s) => s.entries[0].text === '10:12:15');
    expect(minor?.entries.map((e) => [e.text, e.names[0], e.match])).toEqual([
      ['10:12:15', 'Minor Triad', true],
      ['12:15:20', 'Minor Triad 1st inversion', true],
      ['15:20:24', 'Minor Triad 2nd inversion', true],
    ]);
    // with the family filter beside it
    const inFamily = filterLibrary(shapes, { search: 'minor triad', family: 'Minor' });
    expect(inFamily.map((s) => s.entries[0].text)).toContain('10:12:15');
    expect(inFamily.length).toBeLessThan(11);
  });

  it('"dominant seventh" opens the 4:5:6:7 shape in order', () => {
    const found = filterLibrary(shapes, { search: 'dominant seventh' });
    const s = found.find((x) => x.entries[0].text === '4:5:6:7');
    expect(s?.entries.map((e) => e.text)).toEqual(['4:5:6:7', '5:6:7:8', '6:7:8:10', '7:8:10:12']);
    expect(s?.entries[0].names).toEqual(['Harmonic Dominant Seventh']);
    expect(s?.entries[3].names).toEqual(['Harmonic Dominant Seventh 3rd inversion']);
  });

  it('row 14: odd limit up to 9, 4 to 4 notes lists exactly these entries, each with its limits', () => {
    const rows = filterLibrary(shapes, { oddMax: 9, notesMin: 4, notesMax: 4 }).flatMap((s) =>
      s.entries.filter((e) => e.match)
    );
    expect(rows.map((e) => e.text).sort()).toEqual(
      [
        '1/(3:4:5:7)',
        '1/(5:6:7:9)',
        '3:5:7:9',
        '4:5:6:7',
        '4:5:6:9',
        '4:6:7:9',
        '4:6:9:16',
        '5:6:7:8',
        '5:6:7:9',
        '5:6:8:9',
        '6:7:8:10',
        '6:7:8:9',
        '6:8:9:10',
        '6:8:9:12',
        '7:8:10:12',
        '7:9:10:12',
        '9:10:12:14',
        '9:10:12:16',
      ].sort()
    );
    expect(rows.every((e) => e.notes === 4 && e.oddLimit <= 9)).toBe(true);
    expect(rows.find((e) => e.text === '4:5:6:7')).toMatchObject({ oddLimit: 7, primeLimit: 7 });
    expect(rows.find((e) => e.text === '3:5:7:9')).toMatchObject({ oddLimit: 9, primeLimit: 7 });
    expect(rows.find((e) => e.text === '4:6:9:16')).toMatchObject({ oddLimit: 9, primeLimit: 3 });
  });

  it('prime limit and note count filters', () => {
    const f = filterLibrary(shapes, { primeMax: 3 }).flatMap((s) =>
      s.entries.filter((e) => e.match)
    );
    expect(f.length).toBeGreaterThan(0);
    expect(f.every((e) => e.primeLimit <= 3)).toBe(true);
    const n = filterLibrary(shapes, { notesMin: 8 }).flatMap((s) =>
      s.entries.filter((e) => e.match)
    );
    expect(n.every((e) => e.notes >= 8)).toBe(true);
  });
});

describe('joinNames and the stored name', () => {
  it('keeps whole names within the limit', () => {
    expect(joinNames(['A', 'B'])).toBe('A / B');
    expect(joinNames(['x'.repeat(50), 'y'.repeat(20)])).toBe('x'.repeat(50));
    expect(joinNames(['z'.repeat(80)])).toHaveLength(TEMPLATE_NAME_MAX);
  });
});

describe('addLibraryEntries (rows 7, 8, 9, 11)', () => {
  const noMinor = DEFAULT_TEMPLATES.filter((t) => t.text !== '10:12:15');
  const filler = (n: number): ChordTemplate[] =>
    Array.from({ length: n }, (_, i) => ({ text: `${1000 + i}:${1001 + i}` }));

  it('adds a template with its name and family (row 7)', () => {
    const r = addLibraryEntries(noMinor, [byText('10:12:15')], 1200);
    expect(r.refused).toBeUndefined();
    expect(r.added).toEqual([{ text: '10:12:15', name: 'Minor Triad', family: 'Minor' }]);
    expect(r.templates).toEqual([...noMinor, ...r.added]);
    expect(noMinor.some((t) => t.text === '10:12:15')).toBe(false);
  });

  it('joins the names of a merged entry', () => {
    const r = addLibraryEntries([], [byText('1:3:5:15')], 1200);
    expect(r.added[0]).toEqual({
      text: '1:3:5:15',
      name: 'Genus [35] / Major Seventh',
      family: 'Genus and product sets',
    });
  });

  it('refuses an entry with the same notes as a template, naming that template (row 8)', () => {
    const r = addLibraryEntries(DEFAULT_TEMPLATES, [byText('4:5:6')], 1200);
    expect(r.refused).toBe('Same notes as 4:5:6 already in your templates.');
    expect(r.templates).toBe(DEFAULT_TEMPLATES);
    expect(r.added).toEqual([]);
    const spread = addLibraryEntries([{ text: '8:10:12' }], [byText('4:5:6')], 1200);
    expect(spread.refused).toBe('Same notes as 8:10:12 already in your templates.');
    const other = addLibraryEntries([{ text: '1:3:5' }], [byText('4:5:6')], 1200);
    expect(other.refused).toBe('Same notes as 1:3:5 already in your templates.');
  });

  it('adds a whole shape (row 9) and keeps the order', () => {
    const shape = shapeOf('10:12:15')!.entries;
    const r = addLibraryEntries(noMinor, shape, 1200);
    expect(r.added.map((t) => t.text)).toEqual(['10:12:15', '12:15:20', '15:20:24']);
    expect(r.templates).toHaveLength(noMinor.length + 3);
  });

  it('refuses all of it when there are not enough free places (row 9)', () => {
    const shape = shapeOf('10:12:15')!.entries;
    const full = filler(TEMPLATE_LIMIT - 1);
    const r = addLibraryEntries(full, shape, 1200);
    expect(r.refused).toBe('Needs 3 free places; you have 1.');
    expect(r.templates).toBe(full);
    expect(r.added).toEqual([]);
    expect(addLibraryEntries(filler(TEMPLATE_LIMIT), [byText('4:5:6')], 1200).refused).toBe(
      'Needs 1 free place; you have 0.'
    );
    // exactly enough works
    expect(addLibraryEntries(filler(TEMPLATE_LIMIT - 3), shape, 1200).templates).toHaveLength(
      TEMPLATE_LIMIT
    );
    // the limit is a parameter
    expect(addLibraryEntries([], shape, 1200, 2).refused).toBe('Needs 3 free places; you have 2.');
  });

  it('is all or nothing: one duplicate refuses the lot', () => {
    const r = addLibraryEntries(noMinor, [byText('10:12:15'), byText('4:5:6')], 1200);
    expect(r.refused).toBe('Same notes as 4:5:6 already in your templates.');
    expect(r.templates).toBe(noMinor);
    expect(r.added).toEqual([]);
  });

  it('refuses a folding entry with the reason (row 11)', () => {
    const r = addLibraryEntries([], [byText('1:2:3')], 1200);
    expect(r.refused).toBe(FOLD_REASON);
    expect(addLibraryEntries([], [byText('1/(1:2:3:4:5:6:7:8)')], 1200).refused).toBe(FOLD_REASON);
  });

  it('judges the fold in the repeat it is given, not the one the entry was built for', () => {
    // 1:3:5:15 does not fold in 2/1, but in a 3/1 repeat the 3 lands on the root
    expect(byText('1:3:5:15').folds).toBe(false);
    expect(addLibraryEntries([], [byText('1:3:5:15')], 1901.955).refused).toBe(FOLD_REASON);
    // and a stale `folds` flag is not trusted
    expect(
      addLibraryEntries([], [{ ...byText('4:5:6'), folds: true }], 1200).refused
    ).toBeUndefined();
  });

  it('the duplicate rule is the finder key: the same notes once folded into the repeat', () => {
    const key = (t: string) => {
      const p = parseTemplate(t);
      if (!p.ok) {
        throw new Error(p.error);
      }
      return templateKey(p, 1200);
    };
    expect(key('1:3:5')).toBe(key('4:5:6'));
  });

  it('an added template survives the stored limits for every usable entry (name 60, family 40, text 80)', () => {
    for (const e of entries.filter((x) => !x.folds)) {
      const t = addLibraryEntries([], [e], 1200).added[0];
      expect(t.text.length).toBeLessThanOrEqual(80);
      expect((t.name as string).length).toBeLessThanOrEqual(TEMPLATE_NAME_MAX);
      expect((t.family as string).length).toBeLessThanOrEqual(40);
      expect(t.name).toBeTruthy();
      expect(parseTemplate(t.text).ok).toBe(true);
    }
  });
});
