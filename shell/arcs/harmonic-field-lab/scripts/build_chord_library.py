"""Builds src/lib/harmonic-field/chordLibraryData.ts from Scala's chordnam.par (M7a of the harmonic-field-lab arc).

usage (from shell/):
    python -I arcs/harmonic-field-lab/scripts/build_chord_library.py <path to chordnam.par> [output .ts file]

The output defaults to src/lib/harmonic-field/chordLibraryData.ts (next to the lib, found from this script's location).
Format it afterwards with: corepack yarn oxfmt -c oxfmt.config.mjs src/lib/harmonic-field/chordLibraryData.ts

Only the COLON-RATIO entries are kept: a line `a:b:c  Name`, or `(a:b:c)  Name` for the undertone form (written
`1/(a:b:c)` in the lab). Comment lines start with `!`; the other formats (cents, EDO steps, note names) are skipped. A
name that starts with `=` loses the `=` (a syntax marker of the file). The family comes from RULES (first match wins);
an entry that matches none gets `Library`. The script stops with an error when the counts differ from the confirmed
ones (399 entries and the family counts below), so a different chordnam.par is noticed.
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

CREDIT = (
    "Generated by arcs/harmonic-field-lab/scripts/build_chord_library.py from chordnam.par, "
    '"List of chords for Scala" by Manuel Op de Coul (Scala). Do not edit by hand.'
)

# The confirmed family rules (SCENARIOS.M7.md, D4); first match wins.
RULES = [
    ("Neo-Medieval (NM)", r"\bNM\b"),
    ("Bohlen-Pierce (BP)", r"\bBP\b"),
    ("Saturated suspensions (ASS)", r"\bASS\b|Anomalous Saturated"),
    ("Hendrix chords", r"Hendrix"),
    ("Genus and product sets", r"\bGenus\b|Hexany|Dekany|Pentadekany|Eikosany|Tetradekany|\bPentany\b|Octadekany|Tessaradekany"),
    ("Harmonics and subharmonics", r"Harmonics? \d|Subharmonics?|Harmonic (Eleventh|Thirteenth|Fourteenth|Ninth|Dominant|Added)|Undertone|Overtone|Otonal|Utonal"),
    ("Trichords", r"Trichord"),
    ("Tetrachords", r"Tetrachord|Quadrichord"),
    ("Pentachords", r"Pentachord"),
    ("Minor", r"\bMinor\b(?!.*\bMajor\b)"),
    ("Major", r"\bMajor\b"),
    ("Minor", r"\bMinor\b"),
    ("Diminished and augmented", r"Diminished|Augmented|Odim|Quasi-augmented"),
    ("Neutral, subminor and supermajor", r"Subminor|Supermajor|Submajor|Supraminor|Inframinor|Neutral|Ultramajor|Rooted|Subfifth"),
    ("Sevenths, ninths and added tones", r"Seventh|Ninth|Eleventh|Thirteenth|Added|Sixth|6/9|7/m3|7/11"),
    ("Suspended and quartal", r"Suspended|Quartal|Quintal|Fourth|Sus"),
    ("Number sequences", r"Fibonacci|Tribonacci|Lucas|Midas|Squares|Pepper"),
    ("Septimal and higher limits", r"Septimal|Undecimal|Tridecimal|Limit|Marvel|Hyperpyth"),
    ("Named chords", r"mic (Triad|Tetrad|Pentad|Shell)|Orwell|Kestrel|Lambeth|Parizek|Island|Cuthbert|Ratwolf|Petrmic|Nelindic|Augustmic|Joan|Carole|Tristan|Trinidad|Swiss|Battaglia|Nu Chord|Guanyin|Garibert|Nicolic|Cassandra|Starling|Charismic|Untonal|Altered|Super Second|Pythagorean|Isoharmonic|Triunisonus"),
]

EXPECTED_COUNTS = {
    "Named chords": 49,
    "Neo-Medieval (NM)": 47,
    "Pentachords": 39,
    "Sevenths, ninths and added tones": 37,
    "Diminished and augmented": 37,
    "Tetrachords": 31,
    "Neutral, subminor and supermajor": 30,
    "Harmonics and subharmonics": 23,
    "Minor": 22,
    "Major": 17,
    "Hendrix chords": 16,
    "Trichords": 11,
    "Septimal and higher limits": 7,
    "Number sequences": 6,
    "Bohlen-Pierce (BP)": 6,
    "Saturated suspensions (ASS)": 6,
    "Suspended and quartal": 6,
    "Genus and product sets": 5,
    "Library": 4,
}
EXPECTED_TOTAL = 399

LINE = re.compile(r"^(\(?\d+(?::\d+)+\)?)\s+(.*)$")


def family(name):
    for label, pattern in RULES:
        if re.search(pattern, name):
            return label
    return "Library"


def read_entries(par_path):
    entries = []
    for raw in Path(par_path).read_text(encoding="utf8").splitlines():
        line = raw.strip()
        if not line or line.startswith("!"):
            continue
        m = LINE.match(line)
        if not m:
            continue
        spec, name = m.group(1), m.group(2).strip()
        if name.startswith("="):
            name = name[1:].strip()
        if spec.startswith("("):
            if not spec.endswith(")"):
                continue
            text = "1/" + spec
        else:
            if spec.endswith(")"):
                continue
            text = spec
        entries.append({"text": text, "name": name, "family": family(name)})
    return entries


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    par_path = sys.argv[1]
    here = Path(__file__).resolve()
    default_out = here.parents[3] / "src" / "lib" / "harmonic-field" / "chordLibraryData.ts"
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else default_out

    entries = read_entries(par_path)
    counts = Counter(e["family"] for e in entries)
    if len(entries) != EXPECTED_TOTAL or dict(counts) != EXPECTED_COUNTS:
        print("entries:", len(entries), "(expected", EXPECTED_TOTAL, ")")
        for label in sorted(set(counts) | set(EXPECTED_COUNTS)):
            if counts.get(label, 0) != EXPECTED_COUNTS.get(label, 0):
                print("  family", label, counts.get(label, 0), "expected", EXPECTED_COUNTS.get(label, 0))
        sys.exit("The counts differ from the confirmed ones; the file was not written.")

    lines = [
        "/**",
        " * " + CREDIT,
        " * Chord list by Manuel Op de Coul, from Scala (chordnam.par)",
        " *",
        " * Colon-ratio entries only (a:b:c and the undertone form 1/(a:b:c)); %d entries." % len(entries),
        " */",
        "",
        "export interface RawChordEntry {",
        "  /** The lab's template text: `4:5:6`, or `1/(1:2:3)` for an undertone entry. */",
        "  text: string;",
        "  /** The file's name (a leading `=` is dropped). */",
        "  name: string;",
        "  family: string;",
        "}",
        "",
        "export const CHORD_LIBRARY_DATA: readonly RawChordEntry[] = [",
    ]
    for e in entries:
        lines.append(
            "  { text: %s, name: %s, family: %s },"
            % (json.dumps(e["text"]), json.dumps(e["name"], ensure_ascii=False), json.dumps(e["family"]))
        )
    lines.append("];")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf8", newline="\n")
    print("wrote", out_path, "-", len(entries), "entries")
    for label, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print("  ", n, label)


if __name__ == "__main__":
    main()
