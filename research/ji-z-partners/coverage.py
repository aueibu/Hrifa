#!/usr/bin/env python3
"""coverage.py: how much of a proven list each construction explains, and what is left.

Inputs: the chordsum_fs.py tsv (chord sums), the overlap.py tsv (leftover descriptions) and the holegen.py
output jsonl (hole families; matched to list families through the overlap rows they explain is not possible
by id, so the hole count is taken from the holegen summary line "holes in the list ... generated N" plus
"other descriptions M"). The rest is grouped by the overlap.py description.

usage: python coverage.py CHORDSUM_TSV OVERLAP_TSV HOLE_SUM
"""
import collections, re, sys

cs_rows = [l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if not l.startswith("list")]
ov_rows = [l.rstrip("\n").split("\t") for l in open(sys.argv[2]) if not l.startswith("list")]
hs = open(sys.argv[3]).read()
gen = int(re.search(r"generated (\d+); missed", hs).group(1))
other = int(re.search(r"other descriptions (\d+)", hs).group(1))
n = len(cs_rows)
cs = sum(r[6] == "1" for r in cs_rows)
rest = collections.Counter()
for r in ov_rows:
    grp, T, Sp, Sm, P = r[4], r[5], r[6], r[7], r[8]
    if not T:
        rest[f"{grp} (signed both / coefficient 2)"] += 1
        continue
    st = eval(P)
    kind = "hole" if st[0] == 1 else f"merge {st[2]}"
    if kind == "hole" and Sm == "1" and int(T) in (3, 4):
        continue  # generated by holegen
    rest[f"{grp} {kind}: |T| {T}, |S+| {Sp}, |S-| {Sm}"] += 1
lab = cs_rows[0][0]
left = sum(rest.values())
print(f"{lab}: {n:,} families; chord sums {cs:,}; holes (1 hole, 3-4-note chord) {gen:,} "
      f"(+{other} also hole-shaped under another split); explained {cs + gen:,} ({(cs + gen) / n:.2%}); "
      f"left {left:,}")
for k, v in rest.most_common(14):
    print(f"   {v:6,}  {k}")
